import {readFile} from 'node:fs/promises';

// Keep the downloadable game in sync with the same sources used by the website.
export async function makeStandalone() {
  const [html,css,engine,game,favicon]=await Promise.all(
    ['index.html','style.css','src/engine.js','src/game.js','favicon.svg'].map(file=>readFile(file,'utf8'))
  );
  const style=css.replace(/^@import\s+url\([^\n]+\);\s*\n?/m,'');
  const rules=engine.replace(/^export (?=(?:const|function)\b)/gm,'');
  const ui=game.replace(/^import\s+\{[^\n]+\}\s+from\s+['"]\.\/engine\.js['"];\s*\n?/, '');
  const script=`'use strict';\n(()=>{\n${rules}\n${ui}\n})();`;
  if(/^\s*(?:import|export)\s/m.test(script)) throw new Error('Standalone bundle still contains a module dependency');
  function replaceOnce(source,needle,replacement) {
    if(source.split(needle).length!==2) throw new Error(`Standalone template marker missing or duplicated: ${needle}`);
    return source.replace(needle,()=>replacement);
  }
  let output=replaceOnce(html,'  <script type="module" src="./src/game.js"></script>','');
  output=replaceOnce(output,'  <link rel="stylesheet" href="./style.css">',`  <style>\n${style.replace(/<\/style/gi,'<\\/style')}\n  </style>`);
  output=replaceOnce(output,'href="./favicon.svg"',`href="data:image/svg+xml;base64,${Buffer.from(favicon).toString('base64')}"`);
  output=replaceOnce(output,'class="brand" href="./"','class="brand" href="./play.html"');
  output=replaceOnce(output,'</body>',`  <script>\n${script.replace(/<\/script/gi,'<\\/script')}\n  </script>\n</body>`);
  return output.replace('<!doctype html>','<!doctype html>\n<!-- Generated by npm run build. Edit index.html, style.css, and src/ instead. -->');
}
